"""The edge reading pipeline stores what the cloud stores (edge island,
Phase 1, Task 5, svitgrid#1207).

`tests/fixtures/island_pipeline_cases.jsonl` is generated by the cloud's own
pipeline (`services/api/src/__tests__/island-pipeline-contract-fixture.test.ts`
in the monorepo) and replayed here line by line, the edge-only cases too;
`scripts/sync-island-pipeline-cases.sh` vendors it. A case holds its inputs
(`payload`, `inverter`, `prev`, and `principal` when a box sent it) and what
the cloud made of them: `storeData`, `bucketDiff` and `warnings`, or
`rejected` (`schema` for the schema's 400, else the 422 reason).
"""

from __future__ import annotations

import json
import re
from datetime import UTC, datetime
from pathlib import Path

import pytest

from custom_components.svitgrid import edge_reading_pipeline as pipeline

_FIXTURES = Path(__file__).parent / "fixtures"
_CASES = [
    json.loads(line)
    for line in (_FIXTURES / "island_pipeline_cases.jsonl").read_text().splitlines()
    if line.strip()
]
_READING_VALIDATOR_TS = (_FIXTURES / "reading-validator.ts").read_text()

# The cloud's server clock for every case.
_RECEIVED_AT = datetime(2026, 10, 7, 12, 0, 30, tzinfo=UTC)


def _run(case: dict) -> pipeline.PipelineResult:
    principal = case.get("principal", "mobile")
    return pipeline.process(
        case["payload"],
        case["inverter"],
        case["prev"],
        now=_RECEIVED_AT,
        default_source="android-foreground" if principal == "mobile" else principal,
    )


def test_fixture_has_every_case_and_unique_names():
    names = [c["name"] for c in _CASES]
    assert len(names) == 37
    assert len(set(names)) == len(names)
    assert any(c.get("edgeOnly") for c in _CASES)


@pytest.mark.parametrize("case", _CASES, ids=[c["name"] for c in _CASES])
def test_replays_the_cloud_pipeline(case):
    result = _run(case)
    if "rejected" in case:
        assert result.store_data is None
        assert result.rejected == case["rejected"]
        if case["rejected"] != "schema":
            assert result.warnings == case["warnings"]
        return
    assert result.rejected is None
    assert result.store_data == case["storeData"]
    assert result.bucket_diff == case["bucketDiff"]
    assert result.warnings == case["warnings"]


def test_a_millisecond_less_timestamp_is_stored_with_milliseconds():
    case = next(c for c in _CASES if c["payload"]["timestamp"].endswith(":00Z"))
    result = _run(case)
    assert result.store_data["timestamp"] == case["payload"]["timestamp"][:-1] + ".000Z"


def test_process_does_not_mutate_its_inputs():
    case = _CASES[0]
    payload, prev = json.loads(json.dumps(case["payload"])), json.loads(json.dumps(case["prev"]))
    _run(case)
    assert case["payload"] == payload
    assert case["prev"] == prev


def _ts_body(name: str) -> str:
    """The `{ ... }` or `[ ... ]` body after `const <name>`, without comments."""
    start = _READING_VALIDATOR_TS.index(f"const {name}")
    open_at = min(i for i in (_READING_VALIDATOR_TS.find(ch, start) for ch in "{[") if i != -1)
    opener = _READING_VALIDATOR_TS[open_at]
    closer = "}" if opener == "{" else "]"
    depth = 0
    for i in range(open_at, len(_READING_VALIDATOR_TS)):
        ch = _READING_VALIDATOR_TS[i]
        if ch == opener:
            depth += 1
        elif ch == closer:
            depth -= 1
            if depth == 0:
                body = _READING_VALIDATOR_TS[open_at + 1 : i]
                return "\n".join(re.sub(r"//.*$", "", line) for line in body.splitlines())
    raise AssertionError(f"{name} has no closing bracket")


def test_model_tables_match_reading_core():
    entry = re.compile(
        r"(\w+):\s*(?:limitsFromRated\((\d+)\)|\{\s*\.\.\.limitsFromRated\((\d+)\)\s*,?([^}]*)\})"
    )
    limits = {}
    for m in entry.finditer(_ts_body("MODEL_LIMITS")):
        rated = int(m.group(2) or m.group(3))
        overrides = dict(re.findall(r"(\w+):\s*([\w.]+)", m.group(4) or ""))
        assert set(overrides) <= {"maxGridPowerW", "maxBatteryPowerW", "pvTotalIsDcInputRegister"}
        limits[m.group(1)] = pipeline.limits_from_rated(
            rated,
            max_grid_power_w=float(overrides["maxGridPowerW"])
            if "maxGridPowerW" in overrides
            else None,
            max_battery_power_w=float(overrides["maxBatteryPowerW"])
            if "maxBatteryPowerW" in overrides
            else None,
            pv_total_is_dc_input_register=overrides.get("pvTotalIsDcInputRegister") == "true",
        )
    assert len(limits) > 90
    assert limits == pipeline.MODEL_LIMITS

    hv = set(re.findall(r"'(\w+)'", _ts_body("HV_BATTERY_MODELS")))
    assert hv
    assert set(pipeline.HV_BATTERY_MODELS) == hv

    lv = {k: int(v) for k, v in re.findall(r"(\w+):\s*(\d+)", _ts_body("LV_PACK_NOMINAL_V"))}
    assert lv
    assert lv == pipeline.LV_PACK_NOMINAL_V
