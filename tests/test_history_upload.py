# ── the upload ──────────────────────────────────────────────────────────

DEVICE = "edge-ha-1"
INV = "inv-1"
# Left the island at 12:02:30; the bucket that holds it is live's.
RETURN_AT = datetime(2026, 11, 19, 12, 2, 30, tzinfo=UTC)
UNTIL = datetime(2026, 11, 19, 12, 0, tzinfo=UTC)


def _iso(dt: datetime) -> str:
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


def _store(tmp_path) -> ReadingStore:
    return ReadingStore(None, str(tmp_path / "readings.db"))


def _seed(store: ReadingStore, *, raw_hours: int = 30):
    """An island's tables: raw rows every 5 minutes for the last `raw_hours`
    hours before the return, an hourly row for every hour from 100 days back,
    and a daily row for every day from 120 days back."""
    t = UNTIL - timedelta(hours=raw_hours)
    while t < RETURN_AT:
        store._append_sync(
            {
                "inverterId": INV,
                "timestamp": _iso(t),
                "pvPower": 1000.0,
                "gridPower": 0.0,
                "loadPower": 1000.0,
                "batteryPower": 0.0,
                "batterySoc": 50.0,
                "dailyPvEnergy": 1.0,
            }
        )
        t += timedelta(minutes=5)
    conn = store._connect_for_test()
    h = (UNTIL - timedelta(days=100)).replace(minute=0)
    while h < UNTIL:
        r = _hour_row(_iso(h))
        conn.execute(
            "INSERT INTO readings_hourly VALUES (?,?,?,?,?,?)",
            (
                INV,
                r["hour_start"],
                r["sample_count"],
                json.dumps(r["avgs"]),
                json.dumps(r["peaks"]),
                json.dumps(r["energy"]),
            ),
        )
        h += timedelta(hours=1)
    d = (UNTIL - timedelta(days=120)).date()
    while d < UNTIL.date():
        conn.execute(
            "INSERT INTO readings_daily VALUES (?,?,?,?,?,?)",
            (
                INV,
                d.isoformat(),
                2880,
                "{}",
                json.dumps({"pvPower": 3000.0}),
                json.dumps({"dailyPvEnergy": 12.0}),
            ),
        )
        d += timedelta(days=1)
    conn.commit()
    conn.close()


class _Clock:
    def __init__(self, now: datetime):
        self.now = now

    def __call__(self) -> datetime:
        return self.now


class _Cloud:
    """The two history-import routes, answering 200 unless told otherwise."""

    def __init__(self, answers=None):
        self.buckets: list[dict] = []
        self.hours: list[dict] = []
        self.days: list[dict] = []
        self.calls: list[str] = []
        self.answers = list(answers or [])

    def _answer(self):
        if self.answers:
            a = self.answers.pop(0)
            if isinstance(a, Exception):
                raise a
            return a
        return None

    async def import_history(self, api_key, household_id, inverter_id, buckets):
        assert (api_key, household_id, inverter_id) == ("key", "hh-1", INV)
        self.calls.append("buckets")
        a = self._answer()
        if a is not None:
            return a
        self.buckets.extend(buckets)
        return 200, {"imported": len(buckets), "skipped": 0, "latestTs": buckets[-1]["ts"]}

    async def import_history_totals(
        self, api_key, household_id, inverter_id, *, hours=None, days=None
    ):
        assert (api_key, household_id, inverter_id) == ("key", "hh-1", INV)
        self.calls.append("totals")
        a = self._answer()
        if a is not None:
            return a
        self.hours.extend(hours or [])
        self.days.extend(days or [])
        return 200, {
            "hours": {"imported": len(hours or []), "skipped": 0},
            "days": {"imported": len(days or []), "skipped": 0},
        }


def _returned(store: ReadingStore):
    """Record the island, then the return at RETURN_AT."""
    store._note_cloud_copy_sync(DEVICE, False, {INV}, _iso(RETURN_AT - timedelta(days=30)))
    store._note_cloud_copy_sync(DEVICE, True, {INV}, _iso(RETURN_AT))


def _uploader(store, cloud, clock):
    return HistoryUploader(
        store=store,
        api_client=cloud,
        api_key="key",
        household_id="hh-1",
        device_id=DEVICE,
        inverter_ids=[INV],
        tz_name="UTC",
        now=clock,
    )


async def _run_until_idle(up: HistoryUploader, clock: _Clock, max_steps: int = 200) -> list[str]:
    """Steps the uploader, moving the clock over every wait it asks for."""
    results = []
    for _ in range(max_steps):
        result, wait_s = await up.step()
        results.append(result)
        if result == "done":
            return results
        if result in ("wait", "retry", "blocked"):
            clock.now += timedelta(seconds=wait_s)
    raise AssertionError(f"not done after {max_steps} steps: {results[-5:]}")


def _parse(ts: str) -> datetime:
    return datetime.fromisoformat(ts.replace("Z", "+00:00"))


@pytest.mark.asyncio
async def test_the_three_spans_reach_the_cloud_and_each_slot_once(tmp_path):
    store = _store(tmp_path)
    _seed(store)
    _returned(store)
    clock = _Clock(RETURN_AT + timedelta(seconds=5))
    cloud = _Cloud()

    await _run_until_idle(_uploader(store, cloud, clock), clock)

    floor_5min = RETURN_AT - timedelta(days=7)
    # 5-minute buckets: from the first whole hour inside the 7 days, up to the
    # bucket the return falls in, which live ingest owns.
    bucket_ts = [_parse(b["ts"]) for b in cloud.buckets]
    assert bucket_ts == sorted(set(bucket_ts))
    assert bucket_ts[0] == UNTIL - timedelta(hours=30)  # oldest raw row in the store
    assert bucket_ts[-1] == UNTIL - timedelta(minutes=5)
    assert all(t >= floor_5min for t in bucket_ts)
    assert all(b["sampleCount"] == 1 and b["pvPower"] == 1000.0 for b in cloud.buckets)

    # Hours: every whole hour between the hourly and the 5-minute retention,
    # and none twice. Hours under the 5-minute window are the buckets' job.
    hour_ts = [_parse(h["ts"]) for h in cloud.hours]
    assert hour_ts == sorted(set(hour_ts))
    assert all(t + timedelta(hours=1) <= clock.now - timedelta(days=7) for t in hour_ts)
    assert all(t >= clock.now - timedelta(days=90) for t in hour_ts)
    assert hour_ts[-1] == datetime(2026, 11, 12, 12, tzinfo=UTC)
    assert hour_ts[0] == datetime(2026, 8, 21, 14, tzinfo=UTC)

    # Days: the local days before the first day the hourly retention reaches.
    days = [d["date"] for d in cloud.days]
    assert days == sorted(set(days))
    assert days[0] == (UNTIL - timedelta(days=120)).date().isoformat()
    assert days[-1] == "2026-08-20"
    assert all(d["dailyPvEnergy"] == 12.0 for d in cloud.days)

    assert store._history_state_sync(DEVICE)["status"] == "done"


@pytest.mark.asyncio
async def test_the_hour_on_the_seam_waits_until_the_cloud_takes_it_hourly(tmp_path):
    # The return lands mid-hour 7 days after the bucket window opens, so the
    # last hour below the buckets ends after the 5-minute retention begins.
    store = _store(tmp_path)
    _seed(store, raw_hours=200)
    _returned(store)
    clock = _Clock(RETURN_AT + timedelta(seconds=5))
    cloud = _Cloud()
    up = _uploader(store, cloud, clock)

    results = await _run_until_idle(up, clock)

    assert "wait" in results
    bucket_ts = {_parse(b["ts"]) for b in cloud.buckets}
    hour_ts = {_parse(h["ts"]) for h in cloud.hours}
    first_bucket = min(bucket_ts)
    assert first_bucket == datetime(2026, 11, 12, 13, tzinfo=UTC)
    # The hour just below the buckets went up as an hourly total: no gap.
    assert first_bucket - timedelta(hours=1) in hour_ts
    # No hour went up both ways.
    assert not any(
        datetime(t.year, t.month, t.day, t.hour, tzinfo=UTC) in hour_ts for t in bucket_ts
    )


@pytest.mark.asyncio
async def test_a_restart_mid_upload_resumes_from_the_stored_cursor(tmp_path):
    store = _store(tmp_path)
    _seed(store)
    _returned(store)
    clock = _Clock(RETURN_AT + timedelta(seconds=5))
    cloud = _Cloud()

    first = _uploader(store, cloud, clock)
    for _ in range(3):
        await first.step()
    sent_before = len(cloud.calls)
    assert sent_before == 3

    # Home Assistant restarts: a new uploader on the same store.
    await _run_until_idle(_uploader(store, cloud, clock), clock)

    bucket_ts = [b["ts"] for b in cloud.buckets]
    assert len(bucket_ts) == len(set(bucket_ts))
    hour_ts = [h["ts"] for h in cloud.hours]
    assert len(hour_ts) == len(set(hour_ts))
    days = [d["date"] for d in cloud.days]
    assert len(days) == len(set(days))
    # The same total as a run that never stopped.
    (tmp_path / "other").mkdir()
    other = ReadingStore(None, str(tmp_path / "other" / "readings.db"))
    _seed(other)
    _returned(other)
    clock2 = _Clock(RETURN_AT + timedelta(seconds=5))
    cloud2 = _Cloud()
    await _run_until_idle(_uploader(other, cloud2, clock2), clock2)
    assert len(cloud.buckets) == len(cloud2.buckets)
    assert len(cloud.hours) == len(cloud2.hours)
    assert len(cloud.days) == len(cloud2.days)


